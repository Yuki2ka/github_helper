class PlaybackError(RuntimeError):
    pass


def find_program(*names):
    for name in names:
        path = shutil.which(name)
        if path:
            return path
    return None


def _duration_wave(path):
    import wave
    with wave.open(str(path), "rb") as handle:
        frames = handle.getnframes()
        rate = handle.getframerate()
        if rate:
            return frames / float(rate)
    return None


def _duration_ffprobe(path):
    tool = find_program("ffprobe")
    if not tool:
        return None
    result = subprocess.run(
        [tool, "-v", "error", "-show_entries", "format=duration",
         "-of", "default=noprint_wrappers=1:nokey=1", str(path)],
        stdout=subprocess.PIPE, stderr=subprocess.DEVNULL,
        text=True, timeout=15,
    )
    if result.returncode != 0:
        return None
    return float(result.stdout.strip())


def _duration_mutagen(path):
    from mutagen import File as MutagenFile
    audio = MutagenFile(str(path))
    if audio is not None and getattr(audio, "info", None) is not None:
        return float(audio.info.length)
    return None


def _duration_mci(path):
    """Windows MCI duration; avoids decoding or extra packages."""
    if sys.platform != "win32":
        return None
    import ctypes
    buffer = ctypes.create_unicode_buffer(64)
    mci = ctypes.windll.winmm.mciSendStringW
    path = Path(path)
    device = "waveaudio" if path.suffix.lower() == ".wav" else "mpegvideo"
    alias = "txtfromaudio_duration"
    try:
        if mci(f'open "{path}" type {device} alias {alias}', None, 0, 0):
            return None
        try:
            if mci(f"status {alias} length", buffer, 64, 0):
                return None
            milliseconds = float(buffer.value)
        finally:
            mci(f"close {alias}", None, 0, 0)
    except Exception:
        return None
    if milliseconds > 0:
        return milliseconds / 1000.0
    return None


def _duration_pygame(path):
    # pygame.mixer.Sound decodes the whole file into memory. Only use it for
    # small files; mutagen/ffprobe handle the big ones without decoding.
    try:
        if Path(path).stat().st_size > 12 * 1024 * 1024:
            return None
    except OSError:
        return None
    import pygame
    if not pygame.mixer.get_init():
        return None
    sound = pygame.mixer.Sound(str(path))
    return float(sound.get_length())


def detect_duration(path):
    """Best-effort duration in seconds, or None."""
    for probe in (_duration_wave, _duration_ffprobe, _duration_mutagen,
                  _duration_mci, _duration_pygame):
        try:
            value = probe(path)
        except Exception:
            continue
        try:
            if value and float(value) > 0:
                return float(value)
        except (TypeError, ValueError):
            continue
    return None


