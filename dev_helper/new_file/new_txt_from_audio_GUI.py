    def install_audio_support(self):
        if self._installing:
            return
        if not messagebox.askyesno(
            "Install audio support",
            "Install pygame and mutagen into:\n"
            f"{LIBS_DIR}\n\n"
            "pygame plays and seeks audio; mutagen reads durations quickly. "
            "Both are downloaded with pip and keep this folder portable. "
            "Install now?",
        ):
            return
        self._installing = True
        self.log(f"Installing pygame and mutagen into {LIBS_DIR} ...")
        self.set_status("Installing audio packages...")
        threading.Thread(target=self._install_pygame, daemon=True).start()

    def _install_pygame(self):
        LIBS_DIR.mkdir(parents=True, exist_ok=True)
        command = [
            sys.executable, "-m", "pip", "install", "--upgrade",
            "--no-compile", "--target", str(LIBS_DIR), "pygame", "mutagen",
        ]
        try:
            result = subprocess.run(
                command,
                stdout=subprocess.PIPE,
                stderr=subprocess.STDOUT,
                text=True,
                encoding="utf-8",
                errors="replace",
            )
            self.worker_queue.put(
                ("install_done", (result.returncode == 0, result.stdout))
            )
        except Exception as error:
            self.worker_queue.put(("install_done", (False, str(error))))

    def _on_install_done(self, success, output):
        self._installing = False
        tail = "\n".join(str(output).splitlines()[-6:])
        for line in tail.splitlines():
            self.log(line)
        if not success:
            self.set_status("Audio package install failed.")
            messagebox.showerror(
                "Install failed",
                "The audio packages could not be installed. The log has the "
                "details.\n\nPlayback can still work through a system player "
                "such as ffplay.",
            )
            return

        if str(LIBS_DIR) not in sys.path:
            sys.path.insert(0, str(LIBS_DIR))
        import importlib
        importlib.invalidate_caches()
        engine, notes = create_audio_engine()
        if isinstance(engine, NullEngine):
            self.set_status("pygame installed, but no audio backend started.")
            messagebox.showwarning(
                "Installed",
                "pygame is installed, but the audio device could not be "
                "opened. Restart the GUI and try again.",
            )
            return
        if not self.player.set_engine(engine):
            messagebox.showinfo(
                "Installed",
                "pygame is installed. Restart the GUI to use it for playback.",
            )
            return
        self.engine_label.config(text=self._engine_summary())
        if self.install_button is not None:
            self.install_button.destroy()
            self.install_button = None
        self.log(f"Audio backend ready: {self._engine_summary()}")
        self.set_status("Audio support installed. Playback ready.")
        messagebox.showinfo(
            "Audio support ready",
            f"Playback now uses {getattr(engine, 'name', 'the new backend')}.",
        )

