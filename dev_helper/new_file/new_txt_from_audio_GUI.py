    def _next_mark_name(self):
        self._mark_counter += 1
        return f"synctime_{self._mark_counter}"

    def _offset_of_index(self, index):
        # Text.count is much cheaper than copying the text up to the index;
        # it matters when hundreds of marks are saved at once.
        try:
            result = self.editor.count("1.0", index, "chars")
        except Exception:
            result = None
        if result:
            return int(result[0])
        return len(self.editor.get("1.0", index))

    def _index_of_offset(self, offset):
        offset = max(0, int(offset))
        return self.editor.index(f"1.0 + {offset} chars")

    def _word_bounds(self, offset, text=None):
        if text is None:
            text = self.editor_text()
        length = len(text)
        offset = max(0, min(int(offset), length))

        if length == 0:
            return 0, 0

        # Clicking in whitespace snaps to the next word, or to the previous
        # word when the whitespace runs to the end of the text.
        if offset >= length:
            offset = length
            while offset > 0 and text[offset - 1].isspace():
                offset -= 1
        elif text[offset].isspace():
            while offset < length and text[offset].isspace():
                offset += 1
            if offset >= length:
                offset = length
                while offset > 0 and text[offset - 1].isspace():
                    offset -= 1

        if offset < length and text[offset].isspace():
            return 0, 0

        start = offset
        while start > 0 and not text[start - 1].isspace():
            start -= 1
        end = offset
        while end < length and not text[end].isspace():
            end += 1
        return start, end

    def _mark_in_span(self, start, end):
        for name in list(self.marks):
            try:
                offset = self._offset_of_index(self.editor.index(name))
            except tk.TclError:
                continue
            if start <= offset < end:
                return name
        return None

    def _marks_changed(self, save=True):
        self._rebuild_mark_order()
        self._refresh_anchor_tags()
        self._update_sync_status()
        if save:
            self._save_sync_file()

    def _rebuild_mark_order(self):
        self._marks_sorted = sorted(self.marks.items(), key=lambda item: item[1])
        self._mark_times = [entry[1] for entry in self._marks_sorted]

    def _refresh_anchor_tags(self):
        self.editor.tag_remove("anchor", "1.0", "end")
        for name in self.marks:
            try:
                index = self.editor.index(name)
            except tk.TclError:
                continue
            self.editor.tag_add("anchor", index, f"{index} + 1c")
        self.editor.tag_raise("karaoke")

    def _update_sync_status(self):
        count = len(self.marks)
        text = "1 sync mark" if count == 1 else f"{count} sync marks"
        self.sync_status.config(text=text)

    def _active_marks(self, position):
        if not self._marks_sorted:
            return None, None
        index = bisect.bisect_right(self._mark_times, position + 1e-9) - 1
        if index < 0:
            return None, self._marks_sorted[0][0]
        active = self._marks_sorted[index][0]
        following = (
            self._marks_sorted[index + 1][0]
            if index + 1 < len(self._marks_sorted) else None
        )
        return active, following

    def _update_highlight(self, position):
        if not self.follow_var.get() or not self.marks:
            self.editor.tag_remove("karaoke", "1.0", "end")
            return
        active, following = self._active_marks(position)
        if active is None:
            self.editor.tag_remove("karaoke", "1.0", "end")
            self._last_active_mark = None
            return

        try:
            start_index = self.editor.index(active)
        except tk.TclError:
            return
        text_value = self.editor_text()
        start, end = self._word_bounds(
            self._offset_of_index(start_index), text_value
        )
        trimmed = trim_word_range(text_value, start, end)
        if trimmed[0] < trimmed[1]:
            start, end = trimmed
        if following is not None:
            try:
                following_offset = self._offset_of_index(
                    self.editor.index(following)
                )
            except tk.TclError:
                following_offset = None
            if following_offset is not None and start <= following_offset < end:
                end = following_offset

        if end <= start:
            return
        start_index = self._index_of_offset(start)
        end_index = self._index_of_offset(end)

        self.editor.tag_remove("karaoke", "1.0", "end")
        self.editor.tag_add("karaoke", start_index, end_index)

        if active != self._last_active_mark:
            self._last_active_mark = active
            self.editor.see(start_index)
            word = self.editor.get(start_index, end_index).strip()
            if word:
                self.set_status(f"Now: {word}")

    def on_add_mark_click(self, event):
        if self.current_audio is None:
            return "break"
        try:
            index = self.editor.index(f"@{event.x},{event.y}")
            offset = self._offset_of_index(index)
        except tk.TclError:
            return "break"
        start, end = self._word_bounds(offset)
        if start == end:
            return "break"

        position = self.player.position
        if self.player.is_playing:
            position = max(0.0, position - CTRL_CLICK_LEAD_SECONDS)
        position = round(position, 3)

        existing = self._mark_in_span(start, end)
        if existing:
            self.marks[existing] = position
            message = "Updated"
        else:
            name = self._next_mark_name()
            self.editor.mark_set(name, self._index_of_offset(start))
            self.marks[name] = position
            message = "Pinned"
        self._marks_changed(save=True)
        self._update_highlight(self.player.position)
        trimmed = trim_word_range(self.editor_text(), start, end)
        if trimmed[0] < trimmed[1]:
            start, end = trimmed
        word = self.editor.get(
            self._index_of_offset(start), self._index_of_offset(end)
        ).strip()
        self.set_status(f"{message} '{word}' at {format_offset(position)}")

        if self.player.state != "playing" and position <= 0.0:
            self.set_status(
                f"{message} '{word}' at {format_offset(position)} - "
                "play or seek first to pin a real position"
            )
        return "break"

    def on_remove_mark_click(self, event):
        try:
            index = self.editor.index(f"@{event.x},{event.y}")
            offset = self._offset_of_index(index)
        except tk.TclError:
            return "break"
        start, end = self._word_bounds(offset)
        name = self._mark_in_span(start, end)
        if name is None:
            self.set_status("No sync mark on that word.")
            return "break"
        self._remove_mark(name)
        return "break"

    def _remove_mark(self, name):
        time_value = self.marks.pop(name, None)
        try:
            self.editor.mark_unset(name)
        except tk.TclError:
            pass
        self._marks_changed(save=True)
        self._last_active_mark = None
        self.editor.tag_remove("karaoke", "1.0", "end")
        if time_value is not None:
            self.set_status(f"Removed sync mark at {format_offset(time_value)}")

    def clear_sync_marks(self):
        if not self.marks:
            return
        if not messagebox.askyesno(
            "Clear sync marks",
            f"Remove all {len(self.marks)} sync marks from this file?",
        ):
            return
        self._clear_marks_silent()
        self._marks_changed(save=True)
        self._last_active_mark = None
        self.editor.tag_remove("karaoke", "1.0", "end")
        self.set_status("Cleared all sync marks.")

    def _clear_marks_silent(self):
        for name in list(self.marks):
            try:
                self.editor.mark_unset(name)
            except tk.TclError:
                pass
        self.marks.clear()
        self._marks_sorted = []
        self._mark_times = []
        try:
            self.editor.tag_remove("anchor", "1.0", "end")
        except tk.TclError:
            pass

    def _apply_offsets(self, pairs, save=False):
        self._clear_marks_silent()
        length = len(self.editor_text())
        for time_value, offset in pairs:
            offset = max(0, min(int(offset), length))
            name = self._next_mark_name()
            self.editor.mark_set(name, self._index_of_offset(offset))
            self.marks[name] = float(time_value)
        self._marks_changed(save=save)
        return len(pairs)

    def estimate_sync(self):
        if self.current_audio is None:
            messagebox.showinfo("No audio selected", "Select an audio file first.")
            return
        text = self.editor_text()
        if not text.strip():
            messagebox.showinfo("No text", "There is no text to align yet.")
            return
        duration = self.player.duration
        if not duration:
            messagebox.showinfo(
                "Duration unknown",
                "The audio duration could not be detected, so the automatic "
                "estimate is not possible.\n\nUse Ctrl+click marks instead, or "
                "Import timings from a transcript JSON/SRT file.",
            )
            return
        if self.marks and not messagebox.askyesno(
            "Replace marks?",
            f"This replaces the {len(self.marks)} existing sync marks with a "
            "rough estimate. Continue?",
        ):
            return
        pairs = estimate_marks(text, duration)
        self._apply_offsets(pairs, save=True)
        self.log(f"Estimated {len(pairs)} sync points over {format_clock(duration)}.")
        self.set_status(
            f"Estimated {len(pairs)} marks - play and Ctrl+click words to correct them."
        )

    def _save_sync_file(self):
        if self.current_audio is None or self.sync_path is None:
            return
        text = self.editor_text()
        marks = []
        for name, time_value in self.marks.items():
            try:
                offset = self._offset_of_index(self.editor.index(name))
            except tk.TclError:
                continue
            start, end = self._word_bounds(offset, text)
            trimmed = trim_word_range(text, start, end)
            if trimmed[0] < trimmed[1]:
                start, end = trimmed
            marks.append({
                "time": round(float(time_value), 3),
                "offset": int(offset),
                "word": text[start:end],
            })
        marks.sort(key=lambda item: item["time"])

        payload = {
            "version": 1,
            "audio": self.current_audio.name,
            "text": self.text_path.name if self.text_path else "",
            "marks": marks,
        }
        try:
            if marks:
                self.sync_path.write_text(
                    json.dumps(payload, indent=2, ensure_ascii=False) + "\n",
                    encoding="utf-8",
                )
            elif self.sync_path.exists():
                self.sync_path.unlink()
        except OSError as error:
            self.log(f"Could not save sync file: {error}")

    def _load_sync_file(self):
        self._clear_marks_silent()
        if self.sync_path is None or not self.sync_path.exists():
            self._marks_changed(save=False)
            return 0
        try:
            data = json.loads(self.sync_path.read_text(encoding="utf-8"))
            pairs = offsets_from_sync_json(data)
        except (OSError, ValueError) as error:
            self.log(f"Could not read {self.sync_path.name}: {error}")
            return 0
        if not pairs:
            self._marks_changed(save=False)
            return 0
        if not self.editor_text().strip():
            self.log(
                f"{self.sync_path.name} has timings, but the text is empty; "
                "marks were not loaded."
            )
            self._marks_changed(save=False)
            return 0
        self._apply_offsets(pairs, save=False)
        return len(pairs)

    def _auto_import_timings(self):
        if self.current_audio is None or self.marks:
            return
        if not self.editor_text().strip():
            return
        for candidate in timing_candidates(self.current_audio, self.text_path):
            if not candidate.exists():
                continue
            if candidate.suffix.lower() == ".json":
                try:
                    data = json.loads(candidate.read_text(
                        encoding="utf-8-sig", errors="replace"
                    ))
                except (OSError, ValueError):
                    continue
                timings = timings_from_json(data)
            else:
                try:
                    timings = load_timings(candidate)
                except (OSError, ValueError):
                    continue
            if not timings:
                continue
            marks, missed = map_timings_to_text(self.editor_text(), timings)
            if not marks:
                continue
            self._apply_offsets(marks, save=False)
            self.log(
                f"Imported {len(marks)} timing marks from {candidate.name}"
                + (f" ({missed} unmatched)" if missed else "")
            )
            return

    def import_timings_dialog(self):
        if self.current_audio is None:
            messagebox.showinfo("No audio selected", "Select an audio file first.")
            return
        initial = str(self.folder) if self.folder else str(APP_DIR)
        path = filedialog.askopenfilename(
            title="Import word or segment timings",
            initialdir=initial,
            filetypes=[
                ("Timing files", "*.json *.srt *.vtt"),
                ("JSON", "*.json"),
                ("Subtitles", "*.srt *.vtt"),
                ("All files", "*.*"),
            ],
        )
        if path:
            self.import_timings(Path(path))

    def import_timings(self, path):
        path = Path(path)
        try:
            content = path.read_text(encoding="utf-8-sig", errors="replace")
            if path.suffix.lower() in (".srt", ".vtt"):
                timings = parse_srt(content)
                pairs = None
            else:
                data = json.loads(content)
                pairs = offsets_from_sync_json(data)
                timings = timings_from_json(data) if not pairs else []
        except (OSError, ValueError) as error:
            messagebox.showerror("Could not read timings", f"{path}\n\n{error}")
            return

        if pairs:
            marks = pairs
            missed = 0
        else:
            if not timings:
                messagebox.showinfo(
                    "No timings found",
                    f"{path.name} does not contain word or segment timestamps.",
                )
                return
            if not self.editor_text().strip():
                messagebox.showinfo(
                    "No text", "Load or write the companion text first."
                )
                return
            marks, missed = map_timings_to_text(self.editor_text(), timings)

        if not marks:
            messagebox.showinfo(
                "Nothing matched",
                "The timings did not match any words in the text.",
            )
            return
        if self.marks and not messagebox.askyesno(
            "Replace marks?",
            f"Replace the {len(self.marks)} existing sync marks with "
            f"{len(marks)} imported marks?",
        ):
            return
        self._apply_offsets(marks, save=True)
        summary = f"Imported {len(marks)} marks from {path.name}"
        if missed:
            summary += f" ({missed} unmatched)"
        self.log(summary)
        self.set_status(summary)

