def parse_srt(content):
    """Return (seconds, text) for each cue in an SRT or WebVTT file."""
    content = content.replace("\ufeff", "")
    blocks = re.split(r"\r?\n\s*\r?\n", content.strip())
    cues = []
    for block in blocks:
        lines = [line for line in block.splitlines() if line.strip()]
        for position, line in enumerate(lines):
            if "-->" not in line:
                continue
            match = TIMESTAMP_RE.search(line)
            if not match:
                break
            hours, minutes, secs, fraction = match.groups()
            seconds = (
                int(hours or 0) * 3600 + int(minutes) * 60 + int(secs)
                + int(fraction.ljust(3, "0")) / 1000.0
            )
            cue_text = " ".join(lines[position + 1:]).strip()
            if cue_text:
                cues.append((seconds, cue_text))
            break
    return cues


def load_timings(path):
    """Return (seconds, word) pairs from .json, .srt or .vtt."""
    path = Path(path)
    suffix = path.suffix.lower()
    content = path.read_text(encoding="utf-8-sig", errors="replace")
    if suffix in (".srt", ".vtt"):
        return parse_srt(content)
    data = json.loads(content)
    return timings_from_json(data)


def map_timings_to_text(text, timings):
    """Match timed words against the editor text.

    Returns (marks, missed): marks are (seconds, character offset) pairs,
    missed counts words that could not be found in the text.
    """
    marks = []
    missed = 0
    cursor = 0
    last_time = -1.0
    for start, word in timings:
        needle = clean_word(word)
        if not needle:
            continue
        tokens = re.findall(r"[^\W_]+", needle, flags=re.IGNORECASE)
        if not tokens:
            continue
        pattern = re.compile(
            r"(?<!\w)" + r"\W+".join(re.escape(token) for token in tokens)
            + r"(?!\w)",
            re.IGNORECASE | re.UNICODE,
        )
        match = pattern.search(text, cursor)
        if match is None:
            match = pattern.search(text)
        if match is None:
            missed += 1
            continue
        try:
            value = float(start)
        except (TypeError, ValueError):
            missed += 1
            continue
        value = max(value, last_time)
        marks.append((round(value, 3), match.start()))
        last_time = value
        cursor = match.end()
    return marks, missed


def offsets_from_sync_json(data):
    """Return (seconds, offset) pairs from a .sync.json payload."""
    marks = data.get("marks") if isinstance(data, dict) else data
    result = []
    if isinstance(marks, list):
        for item in marks:
            if isinstance(item, dict):
                start = item.get("time", item.get("start"))
                offset = item.get("offset", item.get("char"))
            elif isinstance(item, (list, tuple)) and len(item) >= 2:
                start, offset = item[0], item[1]
            else:
                continue
            if isinstance(start, (int, float)) and isinstance(offset, int):
                result.append((float(start), int(offset)))
    result.sort(key=lambda pair: pair[0])
    return result


def timing_candidates(audio_path, text_path=None):
    """Possible timing sidecars written by a transcriber."""
    audio_path = Path(audio_path)
    candidates = [companion_path(audio_path, SYNC_SUFFIX)]
    for suffix in (".json", ".words.json", ".srt", ".vtt"):
        candidates.append(companion_path(audio_path, suffix))
    if text_path:
        text_path = Path(text_path)
        for suffix in (".json", ".srt", ".vtt"):
            candidates.append(text_path.with_suffix(suffix))

    unique = []
    seen = set()
    for candidate in candidates:
        key = str(candidate).lower()
        if key not in seen:
            seen.add(key)
            unique.append(candidate)
    return unique


