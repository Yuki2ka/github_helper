def scan_audio(folder):
    folder = Path(folder)
    try:
        entries = sorted(folder.iterdir(), key=lambda item: item.name.lower())
    except OSError:
        return []
    return [
        entry for entry in entries
        if entry.is_file() and entry.suffix.lower() in AUDIO_EXTENSIONS
    ]


WORD_RE = re.compile(r"\S+")


def text_words(text):
    """Return (start, end) character offsets for every whitespace run."""
    return [(match.start(), match.end()) for match in WORD_RE.finditer(text)]


def trim_word_range(text, start, end):
    """Shrink a whitespace word span to exclude surrounding punctuation."""
    while start < end and unicodedata.category(text[start]).startswith("P"):
        start += 1
    while end > start and unicodedata.category(text[end - 1]).startswith("P"):
        end -= 1
    return start, end


def estimate_marks(text, duration, lead=ESTIMATE_LEAD_SECONDS,
                   tail=ESTIMATE_TAIL_SECONDS):
    """Spread word marks over the duration, weighted by word length.

    Returns a list of (seconds, character offset), sorted by time.
    This is only an estimate, but it gives a usable karaoke starting point
    that the Ctrl+click marks can later correct.
    """
    words = text_words(text)
    try:
        duration = float(duration)
    except (TypeError, ValueError):
        return []
    if not words or duration <= 0:
        return []

    usable = max(0.1, duration - lead - tail)
    weights = [max(1, end - start) for start, end in words]
    total = float(sum(weights))
    marks = []
    clock = float(lead)
    for (start, _end), weight in zip(words, weights):
        marks.append((round(clock, 3), start))
        clock += usable * weight / total
    return marks


def clean_word(value):
    return re.sub(r"^\W+|\W+$", "", str(value), flags=re.UNICODE)


def timings_from_json(data):
    """Extract (seconds, word) pairs from whisper-like JSON structures.

    Works with whisper.cpp, faster-whisper, whisper-timestamped, stable-ts
    and similar output: words are preferred, segments are used when the
    file only contains segment timestamps.
    """
    words = []
    segments = []

    def walk(node):
        if isinstance(node, dict):
            start = node.get("start")
            if start is None:
                start = node.get("start_time")
            if start is None:
                start = node.get("startTime")
            offsets = node.get("offsets")
            if start is None and isinstance(offsets, dict):
                # whisper.cpp JSON: offsets are milliseconds.
                from_value = offsets.get("from")
                if isinstance(from_value, (int, float)) and not isinstance(from_value, bool):
                    start = float(from_value) / 1000.0
            if isinstance(start, (int, float)) and not isinstance(start, bool):
                text_value = node.get("word")
                if not isinstance(text_value, str) or not text_value.strip():
                    text_value = node.get("text")
                if isinstance(text_value, str) and text_value.strip():
                    entry = (float(start), text_value.strip())
                    if isinstance(node.get("word"), str):
                        words.append(entry)
                    else:
                        segments.append(entry)
            for value in node.values():
                walk(value)
        elif isinstance(node, list):
            for item in node:
                walk(item)

    walk(data)
    result = words or segments
    result.sort(key=lambda item: item[0])
    return result


TIMESTAMP_RE = re.compile(
    r"(?:(\d+):)?(\d{2}):(\d{2})[.,](\d{1,3})"
)


def parse_srt(content):
    """Return (seconds, text) for each cue in an SRT or WebVTT file."""
    content = content.replace("\ufeff", "")
    blocks = re.split(r"\r?\n\s*\r?\n", content.strip())
    cues = []
    for block in blocks:
        lines = [line for line in block.splitlines() if line.strip()]
        for position, line in enumerate(lines):
            if "-->" not in line:
                continue
            match = TIMESTAMP_RE.search(line)
            if not match:
                break
            hours, minutes, secs, fraction = match.groups()
            seconds = (
                int(hours or 0) * 3600 + int(minutes) * 60 + int(secs)
                + int(fraction.ljust(3, "0")) / 1000.0
            )
            cue_text = " ".join(lines[position + 1:]).strip()
            if cue_text:
                cues.append((seconds, cue_text))
            break
    return cues


def load_timings(path):
    """Return (seconds, word) pairs from .json, .srt or .vtt."""
    path = Path(path)
    suffix = path.suffix.lower()
    content = path.read_text(encoding="utf-8-sig", errors="replace")
    if suffix in (".srt", ".vtt"):
        return parse_srt(content)
    data = json.loads(content)
    return timings_from_json(data)


def map_timings_to_text(text, timings):
    """Match timed words against the editor text.

    Returns (marks, missed): marks are (seconds, character offset) pairs,
    missed counts words that could not be found in the text.
    """
    marks = []
    missed = 0
    cursor = 0
    last_time = -1.0
    for start, word in timings:
        needle = clean_word(word)
        if not needle:
            continue
        tokens = re.findall(r"[^\W_]+", needle, flags=re.IGNORECASE)
        if not tokens:
            continue
        pattern = re.compile(
            r"(?<!\w)" + r"\W+".join(re.escape(token) for token in tokens)
            + r"(?!\w)",
            re.IGNORECASE | re.UNICODE,
        )
        match = pattern.search(text, cursor)
        if match is None:
            match = pattern.search(text)
        if match is None:
            missed += 1
            continue
        try:
            value = float(start)
        except (TypeError, ValueError):
            missed += 1
            continue
        value = max(value, last_time)
        marks.append((round(value, 3), match.start()))
        last_time = value
        cursor = match.end()
    return marks, missed


def offsets_from_sync_json(data):
    """Return (seconds, offset) pairs from a .sync.json payload."""
    marks = data.get("marks") if isinstance(data, dict) else data
    result = []
    if isinstance(marks, list):
        for item in marks:
            if isinstance(item, dict):
                start = item.get("time", item.get("start"))
                offset = item.get("offset", item.get("char"))
            elif isinstance(item, (list, tuple)) and len(item) >= 2:
                start, offset = item[0], item[1]
            else:
                continue
            if isinstance(start, (int, float)) and isinstance(offset, int):
                result.append((float(start), int(offset)))
    result.sort(key=lambda pair: pair[0])
    return result


def timing_candidates(audio_path, text_path=None):
    """Possible timing sidecars written by a transcriber."""
    audio_path = Path(audio_path)
    candidates = [companion_path(audio_path, SYNC_SUFFIX)]
    for suffix in (".json", ".words.json", ".srt", ".vtt"):
        candidates.append(companion_path(audio_path, suffix))
    if text_path:
        text_path = Path(text_path)
        for suffix in (".json", ".srt", ".vtt"):
            candidates.append(text_path.with_suffix(suffix))

    unique = []
    seen = set()
    for candidate in candidates:
        key = str(candidate).lower()
        if key not in seen:
            seen.add(key)
            unique.append(candidate)
    return unique


