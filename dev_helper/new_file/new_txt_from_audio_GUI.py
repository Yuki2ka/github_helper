class PygameEngine:
    """pygame.mixer.music: play/pause/seek on every platform."""

    name = "pygame"
    supports_seek = True
    supports_pause = True

    def __init__(self):
        import pygame
        pygame.mixer.init()
        self._pygame = pygame
        self._path = None

    def play(self, path, offset=0.0):
        music = self._pygame.mixer.music
        offset = max(0.0, float(offset))
        try:
            if self._path != str(path):
                music.load(str(path))
                self._path = str(path)
            try:
                # play(start=...): seek by decoding up to the offset.
                music.play(start=offset)
            except Exception:
                # Old SDL_mixer builds reject start=; play, then position.
                music.play()
                if offset > 0:
                    music.set_pos(offset)
        except Exception as error:
            raise PlaybackError(f"pygame could not play this file: {error}")

    def pause(self):
        self._pygame.mixer.music.pause()

    def resume(self):
        self._pygame.mixer.music.unpause()

    def stop(self):
        try:
            self._pygame.mixer.music.stop()
        except Exception:
            pass

    def finished(self):
        return not self._pygame.mixer.music.get_busy()

    def close(self):
        self.stop()
        try:
            self._pygame.mixer.quit()
        except Exception:
            pass


class MciEngine:
    """Windows MCI: built in, plays wav/mp3/wma, supports seeking."""

    name = "MCI"
    supports_seek = True
    supports_pause = True

    ALIAS = "txtfromaudio"

    def __init__(self):
        if sys.platform != "win32":
            raise RuntimeError("MCI is only available on Windows")
        import ctypes
        self._ctypes = ctypes
        self._mci = ctypes.windll.winmm.mciSendStringW
        self._buffer = ctypes.create_unicode_buffer(512)
        self._open = False

    def _send(self, command):
        code = self._mci(command, self._buffer, 512, 0)
        if code:
            raise PlaybackError(f"MCI error {code}: {command}")
        return self._buffer.value

    def play(self, path, offset=0.0):
        self.stop()
        path = Path(path)
        device = "waveaudio" if path.suffix.lower() == ".wav" else "mpegvideo"
        self._send(f'open "{path}" type {device} alias {self.ALIAS}')
        self._open = True
        self._send(f"play {self.ALIAS} from {int(max(0.0, offset) * 1000)}")

    def pause(self):
        if self._open:
            self._send(f"pause {self.ALIAS}")

    def resume(self):
        if self._open:
            self._send(f"resume {self.ALIAS}")

    def stop(self):
        if not self._open:
            return
        try:
            self._send(f"stop {self.ALIAS}")
            self._send(f"close {self.ALIAS}")
        except Exception:
            pass
        self._open = False

    def finished(self):
        if not self._open:
            return True
        try:
            mode = self._send(f"status {self.ALIAS} mode").strip().lower()
        except Exception:
            return True
        return mode in ("stopped", "")

    def close(self):
        self.stop()


class SubprocessEngine:
    """ffplay / mpv / mpg123 / afplay / paplay / aplay.

    Pause is SIGSTOP/SIGCONT on POSIX; seeking restarts the player at the
    new offset. afplay and the raw PCM players cannot seek.
    """

    supports_pause = True

    def __init__(self):
        self._proc = None
        self._paused = False
        self._tool = None
        self._endpoint = None
        self.supports_seek = False

        # SIGSTOP/SIGCONT pause only exists on POSIX. On Windows MCI is the
        # preferred fallback; a bare ffplay can play but not pause.
        self.supports_pause = os.name == "posix"

        candidates = []
        if sys.platform == "darwin":
            candidates.append(("afplay", False))
        candidates.extend([
            ("ffplay", True),
            ("mpv", True),
            ("mpg123", False),
        ])
        if sys.platform != "win32":
            candidates.extend([("paplay", False), ("aplay", False)])

        for name, can_seek in candidates:
            path = find_program(name)
            if path:
                self._tool = path
                self._endpoint = name
                self.supports_seek = can_seek
                break
        if not self._tool:
            raise RuntimeError("no ffplay/mpv/mpg123/afplay available")
        self.name = f"{self._endpoint} (process)"

    def _command(self, path, offset):
        path = str(path)
        offset = max(0.0, float(offset))
        if self._endpoint == "ffplay":
            return [self._tool, "-nodisp", "-autoexit", "-loglevel", "quiet",
                    "-ss", f"{offset:.3f}", path]
        if self._endpoint == "mpv":
            return [self._tool, "--no-video", "--really-quiet",
                    f"--start={offset:.3f}", path]
        return [self._tool, path]

    def play(self, path, offset=0.0):
        self.stop()
        try:
            self._proc = subprocess.Popen(
                self._command(path, offset),
                stdout=subprocess.DEVNULL,
                stderr=subprocess.DEVNULL,
            )
        except OSError as error:
            raise PlaybackError(f"Could not start {self._endpoint}: {error}")
        self._paused = False

    def pause(self):
        if self._proc and self._proc.poll() is None and not self._paused:
            try:
                self._proc.send_signal(signal.SIGSTOP)
                self._paused = True
            except OSError:
                pass

    def resume(self):
        if self._proc and self._proc.poll() is None and self._paused:
            try:
                self._proc.send_signal(signal.SIGCONT)
                self._paused = False
            except OSError:
                pass

    def stop(self):
        process = self._proc
        self._proc = None
        self._paused = False
        if process is None:
            return
        try:
            if process.poll() is None:
                process.terminate()
                try:
                    process.wait(timeout=1.0)
                except subprocess.TimeoutExpired:
                    process.kill()
        except OSError:
            pass

    def finished(self):
        if self._proc is None:
            return True
        if self._paused:
            return False
        return self._proc.poll() is not None

    def close(self):
        self.stop()


def create_audio_engine():
    """Return (engine, notes). Notes explain failed backends."""
    notes = []
    for factory in (PygameEngine, MciEngine, SubprocessEngine):
        try:
            engine = factory()
            return engine, notes
        except Exception as error:
            notes.append(f"{factory.__name__}: {error}")
    return NullEngine(), notes


class AudioPlayer:
    """Playback clock that works the same for every backend.

    The clock is tracked with time.monotonic() instead of asking the
    backend, so highlighting stays smooth and pause-safe.
    """

    def __init__(self, engine=None):
        self.engine = engine or NullEngine()
        self.path = None
        self.duration = None
        self._state = "stopped"       # stopped / playing / paused
        self._base = 0.0
        self._started = None
        self._backend_base = -1.0

    @property
    def available(self):
        return not isinstance(self.engine, NullEngine)

    @property
    def can_seek(self):
        return self.available and getattr(self.engine, "supports_seek", False)

    @property
    def is_playing(self):
        return self._state == "playing"

    @property
    def is_paused(self):
        return self._state == "paused"

    @property
    def state(self):
        return self._state

    @property
    def position(self):
        if self._state == "playing" and self._started is not None:
            value = self._base + (time.monotonic() - self._started)
            if self.duration:
                value = min(value, self.duration)
            return max(0.0, value)
        return max(0.0, self._base)

    def load(self, path):
        self.stop()
        self.path = Path(path)
        self.duration = detect_duration(path)
        self._base = 0.0
        self._backend_base = -1.0
        self._state = "stopped"

    def play(self):
        if self.path is None:
            raise PlaybackError("Select an audio file first.")
        if self._state == "playing":
            return
        start = self._base
        if self.duration and start >= max(0.0, self.duration - 0.02):
            start = 0.0
        try:
            if self._state == "paused" and abs(start - self._backend_base) < 1e-6:
                self.engine.resume()
            else:
                self.engine.play(self.path, start)
                self._backend_base = start
        except PlaybackError:
            raise
        except Exception as error:
            raise PlaybackError(str(error))
        self._base = start
        self._started = time.monotonic()
        self._state = "playing"

    def pause(self):
        if self._state != "playing":
            return
        if not getattr(self.engine, "supports_pause", True):
            # No real pause in this backend. If it can at least start at an
            # offset, stop now and replay from here on resume; otherwise the
            # clock and the audio would drift apart.
            if not self.can_seek:
                self.stop()
                return
            self._base = self.position
            self._started = None
            self._state = "paused"
            self._backend_base = -1.0
            try:
                self.engine.stop()
            except Exception:
                pass
            return
        self._base = self.position
        self._started = None
        self._state = "paused"
        self._backend_base = self._base
        try:
            self.engine.pause()
        except Exception:
            pass

    def toggle(self):
        if self._state == "playing":
            self.pause()
        else:
            self.play()

    def seek(self, seconds):
        if self.path is None:
            return
        try:
            target = max(0.0, float(seconds))
        except (TypeError, ValueError):
            return
        if self.duration:
            target = min(target, self.duration)
        if self._state == "playing":
            try:
                self.engine.play(self.path, target)
            except Exception as error:
                self.stop()
                raise PlaybackError(str(error))
            self._backend_base = target
            self._base = target
            self._started = time.monotonic()
        else:
            if self._state == "paused":
                try:
                    self.engine.stop()
                except Exception:
                    pass
            self._base = target
            self._backend_base = -1.0

    def skip(self, delta):
        self.seek(self.position + float(delta))

    def stop(self):
        try:
            self.engine.stop()
        except Exception:
            pass
        self._base = 0.0
        self._started = None
        self._backend_base = -1.0
        self._state = "stopped"

    def update(self):
        """Advance the clock. Return True when playback just ended."""
        if self._state != "playing":
            return False
        position = self.position
        if self.duration and position >= max(0.0, self.duration - 0.03):
            self._finish(self.duration)
            return True
        try:
            ended = self.engine.finished()
        except Exception:
            ended = False
        if ended:
            self._finish(position)
            return True
        return False

    def _finish(self, position):
        self._base = self.duration if self.duration else position
        self._started = None
        self._state = "stopped"
        self._backend_base = -1.0
        try:
            self.engine.stop()
        except Exception:
            pass

    def set_engine(self, engine):
        if self._state == "playing":
            return False
        try:
            self.engine.close()
        except Exception:
            pass
        self.engine = engine
        self._backend_base = -1.0
        return True

    def close(self):
        self.stop()
        try:
            self.engine.close()
        except Exception:
            pass


